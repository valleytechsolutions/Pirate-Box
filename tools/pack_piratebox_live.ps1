param([string]$ProjectRoot = (Split-Path $PSScriptRoot -Parent))
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

# Mechanical asset packing only. Generated originals and prompts are retained.
# Nearest-neighbor samples preserve pixel edges; no artwork is redrawn here.
$source = @'
using System;
using System.Drawing;
using System.Drawing.Imaging;
using System.IO;
using System.Text;
using System.Collections.Generic;

public static class PirateBoxLivePacker {
  static Rectangle Bounds(Bitmap source, Rectangle cell) {
    int left=cell.Right, top=cell.Bottom, right=cell.Left-1, bottom=cell.Top-1;
    for(int y=cell.Top;y<cell.Bottom;y++) for(int x=cell.Left;x<cell.Right;x++) {
      // Generator may leave imperceptible alpha specks in the empty margins.
      // Only their exclusion from the crop bounds is allowed; pixel alpha in
      // the retained rectangle remains unchanged in the firmware payload.
      if(source.GetPixel(x,y).A<32) continue;
      left=Math.Min(left,x); top=Math.Min(top,y);
      right=Math.Max(right,x); bottom=Math.Max(bottom,y);
    }
    if(right<left) throw new Exception("Empty sprite cell");
    return Rectangle.FromLTRB(left,top,right+1,bottom+1);
  }
  static Bitmap Sample(Bitmap source, Rectangle bounds, int width, int height,
                       double scale, bool bottomAligned) {
    Bitmap result=new Bitmap(width,height,PixelFormat.Format32bppArgb);
    int w=Math.Max(1,(int)Math.Round(bounds.Width*scale));
    int h=Math.Max(1,(int)Math.Round(bounds.Height*scale));
    int dx=(width-w)/2, dy=bottomAligned ? height-2-h : (height-h)/2;
    for(int y=0;y<h;y++) for(int x=0;x<w;x++) {
      int sx=bounds.Left+Math.Min(bounds.Width-1,(int)((x+0.5)*bounds.Width/w));
      int sy=bounds.Top+Math.Min(bounds.Height-1,(int)((y+0.5)*bounds.Height/h));
      result.SetPixel(dx+x,dy+y,source.GetPixel(sx,sy));
    }
    return result;
  }
  static byte[] Pack(Bitmap bitmap) {
    byte[] data=new byte[bitmap.Width*bitmap.Height*3]; int i=0;
    for(int y=0;y<bitmap.Height;y++) for(int x=0;x<bitmap.Width;x++) {
      Color c=bitmap.GetPixel(x,y);
      int rgb=((c.R>>3)<<11)|((c.G>>2)<<5)|(c.B>>3);
      // LV_COLOR_DEPTH=16, LV_COLOR_16_SWAP=1: high byte, low byte, alpha.
      data[i++]=(byte)(rgb>>8); data[i++]=(byte)rgb; data[i++]=c.A;
    }
    return data;
  }
  static Bitmap Unpack(byte[] data,int width,int height) {
    if(data.Length!=width*height*3) throw new Exception("Invalid packed length");
    Bitmap bitmap=new Bitmap(width,height,PixelFormat.Format32bppArgb);int i=0;
    for(int y=0;y<height;y++) for(int x=0;x<width;x++) {
      int rgb=(data[i++]<<8)|data[i++], a=data[i++];
      int r=(rgb>>11)&31, g=(rgb>>5)&63, b=rgb&31;
      bitmap.SetPixel(x,y,Color.FromArgb(a,(r<<3)|(r>>2),(g<<2)|(g>>4),(b<<3)|(b>>2)));
    }
    return bitmap;
  }
  static void WriteArray(StreamWriter output,string name,byte[] bytes) {
    output.WriteLine("static const uint8_t "+name+"[] = {");
    for(int i=0;i<bytes.Length;i++) {
      if(i%24==0) output.Write("  ");
      output.Write("0x"+bytes[i].ToString("X2")+",");
      if(i%24==23) output.WriteLine();
    }
    output.WriteLine("\n};");
  }
  static void WriteBadge(string root,Bitmap preview) {
    var values=new List<ushort>();var runs=new List<ushort>();
    for(int y=0;y<320;y++) for(int x=0;x<320;x++) {
      Color c=preview.GetPixel(x,y);
      values.Add((ushort)(((c.R>>3)<<11)|((c.G>>2)<<5)|(c.B>>3)));
    }
    for(int i=0;i<values.Count;) {
      ushort color=values[i];int count=1;
      while(i+count<values.Count && count<65535 && values[i+count]==color) count++;
      runs.Add((ushort)count);runs.Add(color);i+=count;
    }
    int decoded=0;
    for(int i=0;i<runs.Count;i+=2) for(int n=0;n<runs[i];n++) {
      if(values[decoded++]!=runs[i+1]) throw new Exception("Stock badge RLE mismatch");
    }
    if(decoded!=320*320) throw new Exception("Stock badge length mismatch");
    using(var writer=new StreamWriter(Path.Combine(root,"firmware","src","piratebox_badge_data.inc"),false,new UTF8Encoding(false))) {
      writer.WriteLine("// Generated by tools/pack_piratebox_live.ps1 from live-v3/packed/boot-frame-0.png.");
      writer.WriteLine("static const uint16_t stockRuns[] = {");
      for(int i=0;i<runs.Count;i++) {writer.Write(runs[i]+",");if(i%24==23)writer.WriteLine();}
      writer.WriteLine("\n};");
    }
    var data=new byte[8+values.Count*2];data[0]=68;data[1]=68;data[2]=66;data[3]=49;
    data[4]=64;data[5]=1;data[6]=64;data[7]=1;
    for(int i=0;i<values.Count;i++){data[8+i*2]=(byte)(values[i]>>8);data[9+i*2]=(byte)values[i];}
    File.WriteAllBytes(Path.Combine(root,"media","piratebox-avatar","live-v3","packed","piratebox-stock-happy-320.ddb"),data);
    Console.WriteLine("Stock badge RLE bytes: "+runs.Count*2+"; decoded pixels: "+decoded);
  }
  public static void Run(string root) {
    string assets=Path.Combine(root,"media","piratebox-avatar");
    string packed=Path.Combine(assets,"live-v3","packed");Directory.CreateDirectory(packed);
    string code=Path.Combine(root,"firmware","src","piratebox_boot_data.inc");
    using(Bitmap sheet=new Bitmap(Path.Combine(assets,"live-v3","avatar-sheet.png")))
    using(Bitmap titleSource=new Bitmap(Path.Combine(assets,"pirate-box-title.png")))
    using(StreamWriter output=new StreamWriter(code,false,new UTF8Encoding(false))) {
      if(sheet.Width!=1254 || sheet.Height!=1254) throw new Exception("Reviewed sprite source must be 1254x1254");
      // Cuts lie in the generated sheet's transparent gutters. Its rows are
      // visually spaced rather than exactly equal, so equal quarters clip boots.
      int[] rows={0,335,637,937,1254}, cols={0,320,640,960,1254};
      Rectangle[] bounds=new Rectangle[16];int maxW=0,maxH=0;
      for(int n=0;n<16;n++) {
        Rectangle cell=Rectangle.FromLTRB(cols[n%4],rows[n/4],cols[n%4+1],rows[n/4+1]);
        bounds[n]=Bounds(sheet,cell);
        if(bounds[n].Left<=cell.Left || bounds[n].Top<=cell.Top || bounds[n].Right>=cell.Right || bounds[n].Bottom>=cell.Bottom)
          throw new Exception("Sprite touches crop boundary: "+n);
        maxW=Math.Max(maxW,bounds[n].Width);maxH=Math.Max(maxH,bounds[n].Height);
        Console.WriteLine("Frame "+n+" source bounds "+bounds[n]);
      }
      double scale=Math.Min(141.0/maxW,176.0/maxH);
      output.WriteLine("// Generated by tools/pack_piratebox_live.ps1 from live-v3/avatar-sheet.png. Do not hand-edit.");
      output.WriteLine("// RGB565 (byte-swapped) + original alpha. Assets stay in flash.");
      output.WriteLine("static_assert(LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP == 1, \"Pirate Box artwork expects swapped RGB565\");");
      byte[][] frames=new byte[4][];
      for(int n=0;n<4;n++) {
        using(Bitmap sampled=Sample(sheet,bounds[n],145,180,scale,true)) frames[n]=Pack(sampled);
        File.WriteAllBytes(Path.Combine(packed,"avatar-"+n+".rgb565a"),frames[n]);
        WriteArray(output,"piratebox_avatar_"+n,frames[n]);
      }
      byte[][] liveFrames=new byte[16][];
      double liveScale=Math.Min(44.0/maxW,60.0/maxH);
      for(int n=0;n<16;n++) {
        using(Bitmap sampled=Sample(sheet,bounds[n],48,64,liveScale,true)) liveFrames[n]=Pack(sampled);
        File.WriteAllBytes(Path.Combine(packed,"mascot-"+n+".rgb565a"),liveFrames[n]);
        WriteArray(output,"piratebox_mascot_"+n,liveFrames[n]);
      }
      byte[] title;
      using(Bitmap sampled=Sample(titleSource,new Rectangle(0,0,titleSource.Width,titleSource.Height),260,95,
              Math.Min(260.0/titleSource.Width,95.0/titleSource.Height),false)) title=Pack(sampled);
      File.WriteAllBytes(Path.Combine(packed,"title.rgb565a"),title);
      WriteArray(output,"piratebox_title_pixels",title);
      output.WriteLine("static const lv_img_dsc_t piratebox_avatar_frames[4] = {");
      for(int n=0;n<4;n++) output.WriteLine("  {{LV_IMG_CF_TRUE_COLOR_ALPHA,0,0,145,180},sizeof(piratebox_avatar_"+n+"),piratebox_avatar_"+n+"},");
      output.WriteLine("};");
      output.WriteLine("static const lv_img_dsc_t piratebox_mascot_frames[16] = {");
      for(int n=0;n<16;n++) output.WriteLine("  {{LV_IMG_CF_TRUE_COLOR_ALPHA,0,0,48,64},sizeof(piratebox_mascot_"+n+"),piratebox_mascot_"+n+"},");
      output.WriteLine("};");
      output.WriteLine("static const lv_img_dsc_t piratebox_title = {{LV_IMG_CF_TRUE_COLOR_ALPHA,0,0,260,95},sizeof(piratebox_title_pixels),piratebox_title_pixels};");
      // QA images are reconstructed from the packed bytes used by the firmware.
      using(Bitmap titleDecoded=Unpack(title,260,95))
      using(Bitmap contact=new Bitmap(640,640,PixelFormat.Format24bppRgb))
      using(Graphics contactGraphics=Graphics.FromImage(contact)) {
        contactGraphics.Clear(Color.Black);
        titleDecoded.Save(Path.Combine(packed,"title.png"),ImageFormat.Png);
        for(int n=0;n<4;n++) {
          using(Bitmap frame=Unpack(frames[n],145,180))
          using(Bitmap preview=new Bitmap(320,320,PixelFormat.Format24bppRgb))
          using(Graphics drawing=Graphics.FromImage(preview)) {
            drawing.Clear(Color.Black);
            drawing.DrawImageUnscaled(frame,87,35);
            drawing.DrawImageUnscaled(titleDecoded,30,214);
            frame.Save(Path.Combine(packed,"avatar-"+n+".png"),ImageFormat.Png);
            preview.Save(Path.Combine(packed,"boot-frame-"+n+".png"),ImageFormat.Png);
            if(n==0) WriteBadge(root,preview);
            contactGraphics.DrawImageUnscaled(preview,(n%2)*320,(n/2)*320);
          }
        }
        contact.Save(Path.Combine(assets,"live-v3","boot-packed-preview.png"),ImageFormat.Png);
      }
      using(Bitmap contact=new Bitmap(4*144,4*192,PixelFormat.Format24bppRgb))
      using(Graphics drawing=Graphics.FromImage(contact)) {
        drawing.Clear(Color.FromArgb(5,12,23));
        for(int n=0;n<16;n++) using(Bitmap decoded=Unpack(liveFrames[n],48,64)) {
          decoded.Save(Path.Combine(packed,"mascot-"+n+".png"),ImageFormat.Png);
          // Exact integer enlargement of the decoded firmware pixels for QA.
          for(int y=0;y<64;y++) for(int x=0;x<48;x++) {
            Color c=decoded.GetPixel(x,y);if(c.A==0)continue;
            using(var brush=new SolidBrush(c)) drawing.FillRectangle(brush,(n%4)*144+x*3,(n/4)*192+y*3,3,3);
          }
        }
        contact.Save(Path.Combine(assets,"live-v3","mascot-packed-preview.png"),ImageFormat.Png);
      }
      Console.WriteLine("Embedded bytes: "+(4*145*180*3+260*95*3+16*48*64*3));
    }
  }
}
'@
$references = @(Get-ChildItem -LiteralPath (Join-Path $PSHOME 'ref') -Filter '*.dll' | Where-Object { $_.Name -notlike 'System.Drawing*' } | ForEach-Object { $_.FullName })
$references += @('System.Drawing.Common','System.Drawing.Primitives','System.Private.Windows.GdiPlus','System.Private.Windows.Core')
Add-Type -TypeDefinition $source -ReferencedAssemblies $references
[PirateBoxLivePacker]::Run((Resolve-Path -LiteralPath $ProjectRoot).Path)

$assetDirectory = Join-Path $ProjectRoot 'media\piratebox-avatar'
$hashes = Get-ChildItem -LiteralPath $assetDirectory -Recurse -File | Where-Object { $_.Name -ne 'SHA256SUMS.txt' } | Sort-Object FullName | ForEach-Object {
  '{0}  {1}' -f (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant(), ([IO.Path]::GetRelativePath($assetDirectory,$_.FullName).Replace('\','/'))
}
$hashes | Set-Content -LiteralPath (Join-Path $assetDirectory 'SHA256SUMS.txt') -Encoding utf8
